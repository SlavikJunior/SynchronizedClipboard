package com.github.slavikjunior.synchronizedclipboard.core.crypto

/**
 * Параметры PBKDF2-деривации ключа из парольной фразы.
 *
 * **Соль фиксирована и одинакова на всех устройствах** — это осознанное
 * упрощение MVP: соль не привязана к пользователю, поэтому не защищает от
 * предвычисленных таблиц между разными аккаунтами, но зато позволяет всем
 * клиентам одного пользователя получить идентичный ключ без обмена данными.
 * Post-MVP: per-user случайная соль, хранимая с записью пользователя.
 *
 * 210 000 итераций — рекомендация OWASP для PBKDF2-HMAC-SHA256 на 2023–2026.
 * Дебривация выполняется лениво и кешируется (см. реализации [CryptoManager]),
 * поэтому стоимость оплачивается один раз за сессию.
 */
internal object PassphraseKdf {
    const val SALT = "SyncClip-E2E-PBKDF2-salt-v1"
    const val ITERATIONS = 210_000
    const val KEY_SIZE_BYTES = 32
}
